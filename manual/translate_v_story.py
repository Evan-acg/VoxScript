def parse_srt(filepath: str) -> dict[int, tuple[str, str, str]]:
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    blocks = re.split(r'\n\n+', content.strip())
    entries: dict[int, tuple[str, str, str]] = {}
    for block in blocks:
        lines = block.strip().split('\n')
        if len(lines) < 3:
            continue
        idx = int(lines[0].strip())
        time_range = lines[1].strip()
        text = '\n'.join(lines[2:])
        start, end = time_range.split(' --> ')
        entries[idx] = (start, end, text)
    return entries


def write_srt(entries: dict[int, tuple[str, str, str]], filepath: str) -> None:
    lines: list[str] = []
    for idx in sorted(entries):
        start, end, text = entries[idx]
        lines.append(str(idx))
        lines.append(f"{start} --> {end}")
        lines.append(text)
        lines.append('')
    Path(filepath).write_text('\n'.join(lines), encoding='utf-8')


def main():
    originals = parse_srt(INPUT)
    print(f"Original entries: {len(originals)}")

    translated: dict[int, tuple[str, str, str]] = {}
    for idx in sorted(originals):
        start, end, _ = originals[idx]
        text = TRANSLATIONS.get(idx, "")
        translated[idx] = (start, end, text)

    write_srt(translated, OUTPUT)
    print(f"OK -> {OUTPUT} ({len(translated)} entries)")


